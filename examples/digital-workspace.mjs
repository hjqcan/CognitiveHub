import { CognitiveHub, PluginHost, HumanInbox } from '../dist/index.js';

// Same core, no robot-specific types: a capability installs a reviewed local draft.
const drafts = new Map();
const plugins = new PluginHost();
plugins.install({
  manifest: { apiVersion: 1, id: 'workspace.drafts', version: '0.1.0' },
  setup(ctx) {
    ctx.capability({
      id: 'workspace.create-draft@1', description: 'Create an internal draft from a human-supplied template', effect: 'write',
      async prepare() { return [{ key: 'summary', description: 'Create the supplied internal summary',
        input: { name: 'summary', text: 'Human-reviewed content, not generated by Jev.' }, resources: ['draft:summary'] }]; },
      validate(input) { if (typeof input?.name !== 'string' || typeof input?.text !== 'string') throw new Error('Invalid draft'); },
      async check() { return !drafts.has('summary'); },
      async execute({ action }) { drafts.set(action.input.name, action.input.text); return { status: 'completed', evidence: null }; },
      async verify({ action }) { return { status: drafts.get(action.input.name) === action.input.text ? 'verified' : 'failed',
        evidence: { name: action.input.name, internalOnly: true } }; },
    });
  },
}, ['demo-workspace']);
await plugins.start();
const hub = new CognitiveHub({ plugins, deliberation: new HumanInbox(),
  decision: { name: 'deterministic-demo', async decide(r) { return { kind: 'action', candidateId: r.candidates[0].id }; } },
  state: { async observe() { const now = Date.now(); return { version: `drafts-${drafts.size}`, observedAt: now,
    validUntil: now + 10000, facts: { draftCount: drafts.size } }; } },
  policy: { async check({ action }) { return { allowed: action.capability === 'workspace.create-draft@1',
    version: 'local-demo-policy', reason: 'Local in-memory drafts only' }; } },
});
const p = await hub.propose({ id: 'draft-task', revision: 1, scope: ['demo-workspace'],
  objective: 'Create the internal summary', constraints: ['Never publish'], capabilities: ['workspace.create-draft@1'] });
if (p.kind !== 'proposal') throw new Error('Expected a proposal');
const result = await hub.execute(p.id, 'create-summary-v1', { live: true });
console.log('Digital workspace:', result.record.status);
await plugins.stop('workspace.drafts');
